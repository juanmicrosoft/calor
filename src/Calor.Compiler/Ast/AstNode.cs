internal static class AstVisitorDispatch
{
    public static void Visit(IAstVisitor visitor, AstNode node)
    {
        ArgumentNullException.ThrowIfNull(visitor);
        ArgumentNullException.ThrowIfNull(node);
        switch (node)
        {
