    private static AstNodeSchemaEntry Create<TNode>(string sourceFile)
        where TNode : AstNode
        => new(
            typeof(TNode),
            sourceFile,
            typeof(TNode)
                .GetProperties(System.Reflection.BindingFlags.Public |
                    System.Reflection.BindingFlags.Instance)
                .Where(property => property.GetIndexParameters().Length == 0)
                .Where(property => CanContainAstNode(property.PropertyType))
                .Select(property => property.Name)
                .OrderBy(name => name, StringComparer.Ordinal)
                .ToArray());

    private static bool CanContainAstNode(Type type)
    {
        if (typeof(AstNode).IsAssignableFrom(type))
            return true;
        if (type == typeof(string))
            return false;
        return type.GetInterfaces()
            .Prepend(type)
            .Where(candidate => candidate.IsGenericType)
            .Where(candidate =>
                candidate.GetGenericTypeDefinition() == typeof(IEnumerable<>))
            .Select(candidate => candidate.GetGenericArguments()[0])
            .Any(typeof(AstNode).IsAssignableFrom);
    }
